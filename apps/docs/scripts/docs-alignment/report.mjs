// The findings report. Ordered by consumer impact, not by file name: a wrong
// snippet in getting-started costs a reader their first ten minutes, one in an
// obscure pattern page costs far less.
const SEV_ORDER = { high: 0, medium: 1, advisory: 2 };

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim();

const trunc = (s, n) => (s.length > n ? `${s.slice(0, n).trimEnd()}…` : s);

/**
 * TS diagnostic chains expand `ChatMessage` into two thousand characters of
 * inlined union. The first clause says what was rejected and the LAST clause is
 * the actual root cause (`Type 'string' is not assignable to type '"user" |
 * "assistant"'`), so keep both ends and drop the middle.
 */
function condense(msg, max = 300) {
  const text = String(msg).replace(/\s+/g, ' ').trim();
  if (text.length <= max) return text;
  const clauses = text.split(/\.\s{2,}/).filter(Boolean);
  if (clauses.length >= 2) {
    return `${trunc(clauses[0], 150)}. … ${trunc(clauses[clauses.length - 1], 180)}`;
  }
  return trunc(text, max);
}

function groupBy(items, key) {
  const m = new Map();
  for (const it of items) {
    const k = key(it);
    if (!m.has(k)) m.set(k, []);
    m.get(k).push(it);
  }
  return m;
}

export function renderReport({ findings, flags, coverage, surface, docs, units, commit, summary, skipped, shimmed }) {
  const L = [];
  const p = (s = '') => L.push(s);

  const sorted = [...findings].sort(
    (a, b) =>
      SEV_ORDER[a.severity] - SEV_ORDER[b.severity] ||
      b.impact - a.impact ||
      a.page.localeCompare(b.page) ||
      (a.line ?? 0) - (b.line ?? 0),
  );

  p('# apps/docs vs the shipped API — mechanical alignment report');
  p();
  p(`Generated by \`apps/docs/scripts/docs-alignment/\` at commit \`${commit}\`, against \`@kitn.ai/ui\` ${surface.version} as built into \`packages/ui/dist\`.`);
  p();
  p('**This is a snapshot.** Every name checked here is read at run time from the built `dist/*.d.ts` and from `src/elements/element-meta.json` — nothing is baked into the harness — so the numbers move when the API moves. Re-run rather than trusting the counts below once the surface changes.');
  p();

  // ── mechanism ─────────────────────────────────────────────────────────
  p('## How this was found');
  p();
  p('Doc snippets are fragments: they call the reader\'s own functions, omit imports, and import packages this repo does not install. Compiling them naively produces a wall of false positives and the check gets switched off. The line this harness holds instead:');
  p();
  p('> A snippet referencing the READER\'s code must not fail. A snippet that imports or uses a **kit** symbol that does not exist, or passes a prop a kit component does not accept, must fail.');
  p();
  p('Four mechanisms do that:');
  p();
  p('1. **Unknowns are resolved by the compiler, not guessed.** Compile, collect every `Cannot find name \'X\'`, declare those as `any`, recompile until it settles. The compiler\'s own scope analysis decides what is undeclared. Stubs sit on one prepended line inside a module, so they are scoped to their own snippet and every reported line number is off by exactly one, which is subtracted back out. When the unknown name IS a kit export and the snippet already imports from the kit, the real import is injected instead of an `any` stub, so a fragment that omits an import still gets its props checked.');
  p('2. **Kit modules are never shimmed.** Third-party specifiers that do not resolve become shorthand ambient modules (`any`). `@kitn.ai/ui` and its subpaths are excluded by a hard guard — an unresolved kit entry point or a missing exported member always fails.');
  p('3. **Findings are split by ORIGIN, not by error code.** For each diagnostic the checker is asked where the offending type was *declared*; anything declared under `packages/ui` is kit drift. That is what separates "unknown prop on a kit component" from "unknown prop on the reader\'s own object", and it lets untyped `js` blocks be checked for kit drift only.');
  p('4. **Fragments are interpreted, not rejected.** A block that does not parse as a module is retried as a type shape, a class member, and a bare value; the first interpretation that parses is used. Genuinely malformed code still fails, which the self-test proves.');
  p();
  p('The `kai-*` contract is checked **structurally** against `element-meta.json` rather than by tsc, because the kit\'s shipped React JSX augmentation types every element as `{ [attr: string]: unknown }` and cannot reject a misspelled attribute — and because 132 of the 346 blocks are plain `html` that tsc never sees.');
  p();
  p('Two deliberate exemptions, both self-tested so they cannot silently swallow real findings: snippets the docs explicitly mark as counter-examples (`<!-- Fails — an array can\'t be an HTML attribute -->`), and JSX placeholder children (`{/* your components */}`).');
  p();

  // ── headline ──────────────────────────────────────────────────────────
  p('## Headline');
  p();
  p('| | |');
  p('|---|---|');
  p(`| Pages scanned | ${docs.length} |`);
  p(`| Fenced blocks | ${docs.reduce((n, d) => n + d.blocks.length, 0)} |`);
  p(`| Snippets compiled | ${units.length} |`);
  p(`| Entry points read | ${surface.entries.size} |`);
  p(`| Exported names read | ${[...surface.entries.values()].reduce((n, m) => n + m.size, 0)} |`);
  p(`| \`kai-*\` elements read | ${surface.elements.length} |`);
  p(`| **High-confidence findings** | **${summary.high}** |`);
  p(`| Medium findings | ${summary.medium} |`);
  p(`| Advisory findings | ${summary.advisory} |`);
  p(`| Flagged for human review | ${flags.length} |`);
  p();
  p('### By finding kind');
  p();
  p('| count | kind | what it means |');
  p('|---:|---|---|');
  const KIND_DOC = {
    'kit-type-error': 'a snippet uses a kit symbol/prop/signature that does not typecheck against the shipped `.d.ts`',
    'literal-widening': "a plain object literal widens (`role: 'user'` → `string`) and no longer fits the kit's prop type — a TS reader who copies this does not compile; the fix is the kit's exported `ChatMessage`",
    'undeclared-in-element-meta': 'the kit HAS this (a declarative light-DOM child, or an event it dispatches) but `element-meta.json` does not declare it, so the generated types, docs tables and MCP catalog all omit it — a metadata gap, not a docs error',
    'incompatible-local-type': 'a snippet re-declares a kit type narrower than the real one, and its code breaks against the real one',
    'redeclared-kit-type': 'a snippet re-declares a type the kit already exports (compiles, but teaches a private copy)',
    'unknown-element': 'markup or an MDX component names a `kai-*` element that is not registered',
    'unknown-prop': 'a prop set on a `kai-*` element does not exist on it',
    'unknown-event': 'an event listened for is not declared by that element',
    'unknown-part': 'a `::part()` name is not exposed',
    'unknown-slot': 'a `slot=` name is not declared by any element in the block',
    'unknown-method': 'a method called on an element is not in its public method list',
    'nonscalar-as-attribute': 'an array/object prop is set as an HTML attribute, which stringifies it to `[object Object]`',
    'unknown-kai-token': 'prose backticks a `kai-*` name that is neither an element nor an event',
    'stale-table-entry': 'a table claiming to list kit API names something the kit does not export',
    'unresolved-prose-name': 'prose backticks a PascalCase name no entry point exports and the page never defines (advisory)',
    'stale-kit-api-name': 'prose names something that reads as kit API (it extends a real export family) but that no entry point exports — a consumer cannot import it',
    'stale-member-table-entry': "a hand-written prop/event table on an element's page lists a member that element does not declare",
    'snippet-type-error': 'a type error in a snippet not traceable to a kit type (advisory)',
    'snippet-syntax': 'the snippet does not parse — usually a deliberate elision, occasionally a real defect',
  };
  for (const [kind, n] of summary.byKind) p(`| ${n} | \`${kind}\` | ${KIND_DOC[kind] ?? ''} |`);
  p();

  // ── per section ───────────────────────────────────────────────────────
  p('### By docs section, ranked by consumer impact');
  p();
  p('| section | pages | high | medium | advisory |');
  p('|---|---:|---:|---:|---:|');
  const bySection = groupBy(findings, (f) => f.section);
  const sectionPages = groupBy(docs, (d) => d.section);
  const sections = [...new Set([...sectionPages.keys()])].sort(
    (a, b) => (bySection.get(b)?.filter((f) => f.severity === 'high').length ?? 0) - (bySection.get(a)?.filter((f) => f.severity === 'high').length ?? 0),
  );
  for (const s of sections) {
    const fs = bySection.get(s) ?? [];
    p(
      `| \`${s}\` | ${sectionPages.get(s).length} | ${fs.filter((f) => f.severity === 'high').length} | ${fs.filter((f) => f.severity === 'medium').length} | ${fs.filter((f) => f.severity === 'advisory').length} |`,
    );
  }
  p();

  // ── fix first ─────────────────────────────────────────────────────────
  // The high findings collapse into a handful of root causes; each is one edit
  // repeated across pages, not N independent problems.
  const high = sorted.filter((f) => f.severity === 'high');
  if (high.length) {
    const rootCause = (f) => {
      const d = f.detail;
      const m = /Property '(\w+)' is missing in type .* but required in type '(\w+)'/.exec(d);
      if (m) return `\`${m[2]}\` requires \`${m[1]}\`, which the snippet does not pass`;
      const n = /is not assignable to type 'IntrinsicAttributes & (\w+)'/.exec(d);
      if (n) return `props passed to a component do not satisfy \`${n[1]}\``;
      if (f.kind === 'literal-widening') return "an inline message array widens (`role: 'user'` → `string`) and no longer fits the kit's message type";
      if (f.kind === 'incompatible-local-type') return 'a snippet re-declares a kit type incompatibly';
      return f.kind;
    };
    const groups = groupBy(high, rootCause);
    p('## Fix first');
    p();
    p(`The ${high.length} high-confidence findings collapse into ${groups.size} root cause(s). Each is one edit repeated across pages.`);
    p();
    p('| root cause | pages affected |');
    p('|---|---|');
    for (const [cause, items] of [...groups.entries()].sort((a, b) => b[1].length - a[1].length)) {
      const pages = [...new Set(items.map((i) => `\`${i.page}\`:${i.line}`))];
      p(`| ${esc(cause)} | ${pages.join(', ')} |`);
    }
    p();
  }

  // ── the findings ──────────────────────────────────────────────────────
  for (const sev of ['high', 'medium', 'advisory']) {
    const group = sorted.filter((f) => f.severity === sev);
    if (!group.length) continue;
    p(`## ${sev === 'high' ? 'High-confidence findings' : sev === 'medium' ? 'Medium findings' : 'Advisory findings'} (${group.length})`);
    p();
    if (sev === 'advisory') {
      p('Not gating. Type errors that do not trace back to a kit type, prose names the harness could not resolve, and snippets that re-declare a kit type without actually breaking against it.');
      p();
    }
    const byPage = groupBy(group, (f) => f.page);
    const pages = [...byPage.keys()].sort(
      (a, b) => byPage.get(b)[0].impact - byPage.get(a)[0].impact || a.localeCompare(b),
    );
    for (const page of pages) {
      const items = byPage.get(page).sort((a, b) => (a.line ?? 0) - (b.line ?? 0));
      p(`### \`${page}\` — ${items.length} finding(s)`);
      p();
      p('| line | kind | detail |');
      p('|---:|---|---|');
      for (const f of items) {
        const kind = f.code ? `\`${f.kind}\` ${f.code}` : `\`${f.kind}\``;
        p(`| ${f.line ?? '—'} | ${kind} | ${esc(condense(f.detail))} |`);
      }
      p();
    }
  }

  // ── reverse coverage ──────────────────────────────────────────────────
  p('## Reverse coverage');
  p();
  p('### Shipped but undocumented');
  p();
  p(`**${coverage.undocumentedElements.length} \`kai-*\` element(s) are never mentioned anywhere in \`apps/docs\`:**`);
  p();
  p(coverage.undocumentedElements.length ? coverage.undocumentedElements.map((t) => `\`${t}\``).join(', ') : '_none_');
  p();
  p(`**${coverage.elementsWithoutPage.length} element(s) are mentioned but have no \`<Playground>\`/\`<Example>\`/\`<PropTable>\` of their own** (named in passing only):`);
  p();
  if (coverage.elementsWithoutPage.length) {
    p('| element | mentioned in |');
    p('|---|---|');
    for (const e of coverage.elementsWithoutPage) p(`| \`${e.tag}\` | ${e.mentionedIn.slice(0, 4).map((x) => `\`${x}\``).join(', ')}${e.mentionedIn.length > 4 ? ` +${e.mentionedIn.length - 4}` : ''} |`);
  } else p('_none_');
  p();
  p(`**${coverage.undocumentedComponents.length} SolidJS component export(s) are never named in the docs** (of ${surface.components.size} detected components on the root entry):`);
  p();
  p(coverage.undocumentedComponents.length ? coverage.undocumentedComponents.map((n) => `\`${n}\``).join(', ') : '_none_');
  p();

  p('### Documented but gone');
  p();
  p(`**${coverage.staleTags.length} \`kai-*\` token(s) appear in the docs but are neither a registered element nor a declared event:**`);
  p();
  if (coverage.staleTags.length) {
    p('| token | pages |');
    p('|---|---|');
    for (const t of coverage.staleTags) p(`| \`${t.tag}\` | ${t.pages.map((x) => `\`${x}\``).join(', ')} |`);
  } else p('_none_');
  p();
  p(`**${coverage.staleEntries.length} \`@kitn.ai/ui\` subpath(s) referenced in the docs are not in the package's exports map:**`);
  p();
  if (coverage.staleEntries.length) {
    p('| specifier | pages |');
    p('|---|---|');
    for (const e of coverage.staleEntries) p(`| \`${e.spec}\` | ${e.pages.map((x) => `\`${x}\``).join(', ')} |`);
  } else p('_none_');
  p();

  // ── flag for human ────────────────────────────────────────────────────
  p('## Flagged for human review');
  p();
  p('Executable factual claims the harness extracted but cannot adjudicate. It does **not** guess whether these are true — someone has to check each against the build output, the exports map, or the running app.');
  p();
  const byCat = groupBy(flags, (f) => f.category);
  const CAT_DOC = {
    packaging: 'claims about what the package ships, how it resolves, and what the bundler does with it',
    runtime: 'claims about SSR, server rendering, hydration and where code runs',
    default: 'claims about default values and automatic behaviour',
    version: 'claims tied to a version number',
    'size-perf': 'claims about bundle size, code splitting and lazy loading',
  };
  for (const [cat, items] of [...byCat.entries()].sort((a, b) => b[1].length - a[1].length)) {
    p(`### \`${cat}\` (${items.length}) — ${CAT_DOC[cat] ?? ''}`);
    p();
    p('| page | line | claim |');
    p('|---|---:|---|');
    for (const f of items.sort((a, b) => b.impact - a.impact || a.page.localeCompare(b.page))) {
      p(`| \`${f.page}\` | ${f.line} | ${esc(f.text)} |`);
    }
    p();
  }

  // ── what the harness could not reach ──────────────────────────────────
  p('## Honest assessment: how much of the drift is mechanically detectable');
  p();
  p('Roughly **a third**, and it is the cheap third.');
  p();
  p('What a machine settles conclusively: does this name exist, does this prop exist, does this element exist, does this event exist, does this snippet compile against the shipped types, is this local type compatible with the kit\'s. Every finding above is one of those, and each is either true or false with no judgement involved. That is the whole first two sections of this report.');
  p();
  p('What it cannot settle, and where the rest of the drift lives:');
  p();
  p('- **Whether a snippet that compiles actually works.** Nothing here is executed. The parts-flattening bug in `guides/frameworks/solid.mdx` compiled cleanly for as long as it existed, and was only caught because the page happened to re-declare a type the kit exports. A page that flattens `parts` without re-declaring anything would still be invisible.');
  p('- **Whether prose is true.** Names are checked; claims are not. The 47 items flagged for human review are the ones worth checking, and the harness deliberately refuses to guess at any of them.');
  p('- **Whether the recommended approach is still the recommended approach.** A page can be entirely correct and entirely outdated.');
  p('- **Whether an example is good.** Ordering, completeness, error handling, whether the snippet teaches the pattern the kit wants taught.');
  p();
  p('The honest framing: this harness makes the mechanical third *free and repeatable*, and it makes the other two thirds **visible and bounded** — 47 extracted claims and two reverse-coverage lists are a finite human task, where "read 120 pages and check everything" is not. It is a filter, not a verdict.');
  p();
  p('One more caveat worth stating plainly: this harness has already been wrong. Its first full run reported 73 high-confidence findings; 64 of those were its own bugs (Vue\'s `.prop` modifier, Svelte\'s `{messages}` shorthand, a CSS custom property parsed as an element, prose inside comments, the docs\' own counter-examples). Each was found by checking a sample of findings against the source by hand. The number below is what survived that; it is not proof that nothing else is wrong with it.');
  p();
  p('## What this harness does NOT cover');
  p();
  p('Stated plainly, because a coverage claim nobody bounded is how a check ends up proving nothing.');
  p();
  p('- **Prose meaning.** Only names are checked, not sentences. "`ChatContainer` owns the scroll" is unverifiable here; the harness only knows `ChatContainer` exists.');
  p('- **Runtime behaviour.** No snippet is executed and no page is rendered. A snippet that compiles and renders nothing looks identical to a correct one.');
  p('- **Visual/UX claims.** Screenshots, layout, theming results.');
  p('- **Untyped JS depth.** `js` and inline `<script>` blocks are checked for kit-API drift only. A logic bug in an untyped snippet is invisible.');
  p(`- **Non-code fences.** ${skipped.length} block(s) in languages with no checker here (${[...new Set(skipped.map((s) => s.lang))].sort().join(', ') || 'none'}).`);
  p(`- **Uninstalled third-party packages.** ${shimmed.length} specifier(s) resolve to \`any\` by design, so misuse of them is not caught: ${shimmed.slice(0, 20).map((s) => `\`${s}\``).join(', ')}${shimmed.length > 20 ? ` +${shimmed.length - 20}` : ''}.`);
  p('- **Angular / Vue / Svelte templates.** Only the `<script>` half is compiled; the template half gets the same structural `kai-*` checks as HTML.');
  p();
  p('## Reproducing');
  p();
  p('```bash');
  p('pnpm exec nx build ui                       # the harness reads dist/*.d.ts');
  p('pnpm --filter @kitn.ai/docs run verify:docs # gate: exits 1 on any high finding');
  p('pnpm --filter @kitn.ai/docs run verify:docs:report  # regenerate this file');
  p('```');
  p();
  p('### CI status: NOT wired in yet');
  p();
  p('Deliberately. Cost is not the reason — the whole run is about 10s and needs no network, which is well inside what the required job already spends on `verify:scaffold`. Two things have to be true first:');
  p();
  p('1. **The tree has to be green.** A gate added while it reports findings is a gate that is red on arrival, and a red-on-arrival gate gets bypassed rather than fixed. Fix the `Fix first` table, then wire it.');
  p('2. **It needs one more adversarial pass.** The first full run reported 73 high-confidence findings and 64 were the harness\'s own bugs. That ratio came down by hand-checking findings against the source. It is now 11, all of which were verified by reading the page — but the harness has not yet survived anyone deliberately trying to make it lie.');
  p();
  p('Suggested sequencing: land it as a non-blocking job that posts the report, watch it for a few PRs, then promote it to required once the high count has stayed at zero on its own.');
  p();
  p('The self-test runs first, every time. It compiles five snippets that MUST produce a kit finding (unknown entry point, unknown export, bogus prop on a kit component, wrong argument type, removed wire API), seven structural probes that MUST report (unknown element, unknown prop, non-scalar-as-attribute, unknown event, unknown part, stale `<Example tag>`, stale `<Example config>` key), a shadow probe that must go from clean to broken when the real type is substituted, and five probes that MUST stay silent (reader-owned undeclared names, omitted imports, uninstalled third-party imports, valid markup, non-scalar props bound as JSX expressions). If any probe misbehaves the run aborts before touching the docs, because a green result would be meaningless.');
  p();

  return L.join('\n');
}
