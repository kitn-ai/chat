const PROVIDERS = ['openai', 'anthropic', 'jsonschema'] as const;

/**
 * What a caller gets when they do not name a provider.
 *
 * NOT a coin-flip between the two wire formats, and deliberately not "serve all
 * three". The three envelopes are not interchangeable in a way a reader can patch
 * up: OpenAI nests the schema at `function.parameters`, Anthropic puts it flat at
 * `input_schema`. Handing over one of those unasked means a harness on the other
 * provider pastes it in and gets a 400 it will blame on the kit.
 *
 * `jsonschema` is the only one of the three that is not a wire envelope at all —
 * `{ name, description, schema }` cannot be mistaken for either provider's shape, so
 * a caller who reads it as one is corrected by the field names before they ship it.
 * It is also directly usable, not a booby prize: `tool({ inputSchema: jsonSchema(
 * def.schema) })` is exactly what the Vercel AI SDK wants, and of the nine
 * integrations this MCP scaffolds, exactly one (openrouter) posts a raw OpenAI-wire
 * tools array; the rest go through an SDK or an agent framework that takes the bare
 * schema.
 *
 * Serving all three was the other candidate and it loses on cost for no gain in
 * safety: measured on this tree, one card's pretty-printed definition runs
 * 1.7-5.3 KB, so three of them plus the schema turns a single `kai-artifact` lookup
 * into roughly 20 KB of context. The response names all three modes and the exact
 * call that produces each, so a caller who does know their provider is one re-ask
 * away and still never invents an envelope.
 */
const DEFAULT_PROVIDER: ToolProvider = 'jsonschema';

function isProvider(value: string): value is ToolProvider {
  return (PROVIDERS as readonly string[]).includes(value);
}

/** Stable fence info strings, so a reader (and reference.test.ts) can lift the blocks back out exactly. */
const TOOL_FENCE = 'kai-tool-definition';
const SCHEMA_FENCE = 'kai-card-schema';

function fence(info: string, value: unknown): string[] {
  return ['```json ' + info, JSON.stringify(value, null, 2), '```'];
}

/**
 * Render a card type as it would be written in JS source.
 *
 * The seven built-ins are all bare identifiers, but a card type is whatever string a
 * developer put in `CardEnvelope.type` — `pricing-table` is legal and reaches this
 * code the day an eighth built-in is hyphenated. Emitting `{ pricing-table: … }` as a
 * copy-paste sample would be a syntax error, so the quoting is decided, not assumed.
 */
const BARE_IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function asKey(cardType: string): string {
  return BARE_IDENTIFIER.test(cardType) ? cardType : JSON.stringify(cardType);
}

function asMember(cardType: string): string {
  return BARE_IDENTIFIER.test(cardType) ? `.${cardType}` : `[${JSON.stringify(cardType)}]`;
}

/**
 * The loop, in the four facts a harness cannot infer from a prop table.
 *
 * Shared by the card-backed and the card-host sections because they are the same
 * contract seen from the two ends, and a second copy would be the drift this whole
 * task exists to remove, one level up from the tool definition.
 *
 * `example` is the card the caller actually asked about, so the illustration is about
 * their card rather than a fixed one they then have to translate.
 */
function loopWiring(example: string): string[] {
  return [
    '',
    '#### Wiring the loop',
    `- **Tool names are \`${KAI_TOOL_PREFIX}<card type>\`.** \`${toolNameForCardType(example)}\` produces \`{ type: "${example}" }\`. ` +
      'Use `isCardTool(name)` to split card calls from your own tools; never match the prefix by hand.',
    '- **`tool_call_id` becomes `CardEnvelope.id`, unchanged.** That is what makes a revision UPSERT: ' +
      'a model that re-sends the same tool call id replaces the card in place instead of rendering a second copy of it. ' +
      'Generating your own id breaks that silently.',
    '- **`cardFromToolCall(name, input, { id: call.id })`** turns the call into a renderable envelope, ' +
      'or returns `null` when it is one of your own tools so the loop falls through to it. It never throws.',
    '- **Everything above is one import:** `import { cardTools, cardFromToolCall, isCardTool } from \'@kitn.ai/ui/schemas\'`. ' +
      `The raw documents also ship as JSON (\`@kitn.ai/ui/schemas/${example}.schema.json\`) for a Python or Go backend.`,
  ];
}

/** The card-backed section: schema + a GENERATED tool definition. */
function renderCardContract(tag: string, cardType: CardSchemaName, provider: ToolProvider): string[] {
  const schema = cardSchemas[cardType];

  // GENERATED, NEVER RESTATED.
  //
  // This calls the same `cardTools` a consumer's route calls, on the same schema, so
  // the definition served here cannot diverge from the one they ship — not when a
  // schema gains a field, not when the projection changes what it strips. A literal
  // typed into this file would read identically today and rot on the first schema
  // change, which is exactly the hand-copy drift this tool exists to remove.
  // reference.test.ts asserts byte-equality against BOTH `cardTools({ [type]: schema },
  // …)` and the matching entry of the whole-registry `cardTools({ provider })`, so a
  // hand-edit here fails a test rather than shipping.
  const [def] = cardTools({ [cardType]: schema }, { provider });

  const lines: string[] = [
    '',
    '### Card contract',
    `\`<${tag}>\` renders \`CardEnvelope.type: "${cardType}"\`. A model does not emit an envelope; ` +
      `it calls the tool \`${toolNameForCardType(cardType)}\`, and the kit turns that call back into one.`,
  ];

  lines.push(
    '',
    `#### Tool definition — provider \`${provider}\``,
    `Generated by \`cardTools({ ${asKey(cardType)}: cardSchemas${asMember(cardType)} }, { provider: '${provider}' })\`. ` +
      'Copy it; do not retype it, and do not hand-maintain a second copy — regenerate instead.',
    `Ask again with \`provider\` set to \`openai\`, \`anthropic\` or \`jsonschema\` for the other envelopes. ` +
      'They are NOT interchangeable: OpenAI nests the schema at `function.parameters`, Anthropic puts it flat at `input_schema`.',
    ...fence(TOOL_FENCE, def),
  );

  lines.push(
    '',
    '#### Card data JSON Schema',
    `\`import { cardSchemas } from '@kitn.ai/ui/schemas'\` → \`cardSchemas${asMember(cardType)}\`. ` +
      `Raw document: \`@kitn.ai/ui/schemas/${cardType}.schema.json\`.`,
    'This is the authored contract, and it is what `registry.validate()` checks arriving data against. ' +
      'The tool definition above carries the same document with `$schema`, `$id` and `x-kai-*` stripped — ' +
      'that projection is `cardTools`\' job, so do not put a raw schema on the wire yourself.',
    ...fence(SCHEMA_FENCE, schema),
  );

  lines.push(...loopWiring(cardType));
  return lines;
}

/** The card-host section: no schema of its own, but this is where the props live. */
function renderCardHost(tag: string): string[] {
  const rows = cardSchemaNames.map((type) => {
    const cardTag = cardTagForType(type);
    return `- \`${type}\` → \`<${cardTag ?? '(no element)'}>\`, tool \`${toolNameForCardType(type)}\``;
  });

  return [
    '',
    '### Card contract',
    `\`<${tag}>\` renders generative-UI cards inside the thread. It is a HOST: it draws whatever ` +
      'envelopes arrive, and carries the two props that say what a card may be.',
    '',
    '- **`cardTypes`** — `Record<envelope type, custom element tag>`. What DRAWS a card. ' +
      `Merged over the built-ins, so your entry overrides ours and the other ${cardSchemaNames.length - 1} still render.`,
    '- **`cardSchemas`** — `Record<envelope type, JSON Schema>`. What a VALID card looks like. ' +
      `This is the prop that carries YOUR OWN card schemas into the browser validator; the ${cardSchemaNames.length} built-ins are already known. ` +
      'Both are objects, so both are JS properties (`el.cardSchemas = …`), never HTML attributes.',
    '',
    'Write both once with `createCardRegistry({ use, custom })` from `@kitn.ai/ui/schemas` and thread it to both ends: ' +
      '`el.cardTypes = cards.tags` / `el.cardSchemas = cards.validationSchemas` on the client, `cardTools(cards, { provider })` on the route.',
    '',
    'Built-in card types (ask `component_reference` for one of these tags to get its schema and tool definition):',
    ...rows,
    ...loopWiring(cardSchemaNames[0]),
  ];
}

