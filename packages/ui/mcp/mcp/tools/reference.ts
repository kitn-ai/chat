/**
 * The `/state` + `/wire` appendix (rung-6 F-46): a marker-fenced section of the
 * package-root `llms-full.txt`, which `build:api` DERIVES from the shipped
 * `dist/state/*.d.ts` + `dist/wire/*.d.ts` (scripts/gen-llms-programmatic.mjs).
 * Read, never restated: this tool restating one signature by hand is exactly
 * the drift the generator exists to remove. The root copy is the CANONICAL and
 * ONLY shipped copy (owner-ruled 2026-08-25): a second copy under `dist/llms/`
 * used to ship too, ~293 KB of duplicate tarball weight — and it once went
 * stale against the root while both claimed to be the artifact. It resolves
 * relative to the manifest (`dist/custom-elements.json`), whose parent's
 * parent is the package root in both contexts — bundled bin and source/vitest.
 */
/**
 * The fence gen-llms-programmatic.mjs writes around the section inside
 * llms-full.txt. REGISTERED COPY of `PROGRAMMATIC_MARKERS` in that script —
 * this TS module cannot import the generator .mjs. If either side moves, the
 * slice below misses and the reference tests fail on the "Missing build
 * artifact" branch, so the drift is loud.
 */
const PROGRAMMATIC_START = '<!-- kai:programmatic:start -->';
const PROGRAMMATIC_END = '<!-- kai:programmatic:end -->';

function renderProgrammaticAppendix(): string {
  // Sliced out of the SHIPPED llms-full.txt rather than served from a file of
  // its own: a standalone copy was ~50 KB of duplicate tarball weight
  // (verify:pack priced it), and slicing keeps one derivation with zero extra
  // shipped bytes.
  const path = join(dirname(resolveManifestPath()), '..', 'llms-full.txt');
  const missing = (what: string) =>
    `Missing build artifact: ${what}\n\n` +
    'The programmatic-layer reference is generated from the shipped dist/*.d.ts by the ' +
    'build (a marker-fenced section of the package-root llms-full.txt). Run `nx build ui` ' +
    '(or `npm run build:api` in packages/ui) and ask again. It is deliberately not restated ' +
    'here: a hand-typed copy would drift from the declarations your editor shows.';
  if (!existsSync(path)) return missing(path);
  const full = readFileSync(path, 'utf-8');
  const start = full.indexOf(PROGRAMMATIC_START);
  const end = full.indexOf(PROGRAMMATIC_END);
  if (start === -1 || end === -1 || end <= start) {
    return missing(`the ${PROGRAMMATIC_START} section inside ${path}`);
  }
  return full.slice(start + PROGRAMMATIC_START.length, end).trim();
}

/**
 * One code recipe as files a builder pastes. The catalog half (ingredients,
 * wiring edges, invariants — each executed by surfaces.test.ts) is the surface
 * recipe of the same id; this is the body a data record cannot carry, and
 * `verify:scaffold` compiles every `lang: 'ts'` file of it.
 */
function renderCodeRecipe(r: CodeRecipe): string {
  const lines: string[] = [
    `## Recipe: ${r.title} (\`${r.id}\`)`,
    '',
    r.intent,
    '',
    `**Elements composed:** ${r.ingredients.map((t) => `\`<${t}>\``).join(', ')}`,
    '',
    '**Read these before pasting:**',
    ...r.notes.map((n) => `- ${n}`),
  ];
  for (const f of r.files) {
    lines.push('', `### \`${f.path}\``, '', '```' + f.lang, f.code.trimEnd(), '```');
  }
  lines.push(
    '',
    'The wiring topology, invariants and composition claims behind this recipe are the ' +
      `surface recipe of the same id — call component_reference with { name: "recipes" }.`,
  );
  return lines.join('\n');
}

/**
 * The payload out of `CustomEvent<T>`, or `undefined` when there is no payload.
 *
 * The manifest types every event, but as the wrapper — printing that raw teaches
 * a reader to write `CustomEvent<...>` where a payload belongs. Anything that is
 * not of the form `CustomEvent<…>` has NO payload to print, and this returns
 * `undefined` so the caller omits the `detail` clause entirely.
 *
 * That is read off the generator rather than guessed at. gen-element-api.mjs
 * writes the CEM type as ``CustomEvent<${e.detail}>`` when the element declares a
 * detail and the bare string `CustomEvent` when it does not — exactly two shapes,
 * and the bare one means the detail is `void` (e.g. `'kai-click': void` in
 * button.tsx). Passing an unrecognised type through unchanged looked like a safe
 * fallback for an already-unwrapped payload; what it actually caught was the void
 * events, which then rendered ``Carries no detail. `detail`: `CustomEvent` `` — a
 * line contradicting itself, on 13 events across 10 elements. The whole-manifest
 * probe in reference.test.ts holds both directions of the rule.
 */
function eventDetail(typeText: string | undefined): string | undefined {
  const m = /^CustomEvent<([\s\S]*)>$/.exec(typeText?.trim() ?? '');
  return m ? m[1].trim() || undefined : undefined;
}

function formatReference(tag: string, provider: ToolProvider): string {
  const el = getElement(tag);

  if (!el) {
    const all = listElements();
    const sample = all.slice(0, 5).join(', ');
    return (
      `Unknown element: ${tag}\n\n` +
      `Valid tags include: ${sample} (and ${Math.max(0, all.length - 5)} more).\n` +
      `Call component_reference with no name (or name: "list") to list all ${all.length} elements.`
    );
  }

  const lines: string[] = [];

  // ── Header ─────────────────────────────────────────────────────────────────
  lines.push(`## <${tag}>`);
  if (el.description) {
    lines.push('', el.description.trim());
  }

  // ── Getting the element ────────────────────────────────────────────────────
  // FIRST, above every other section. An element that never upgrades renders
  // nothing and logs NOTHING: the property assigns and reads back fine, and
  // whenDefined() never settles, so the listener is never attached. That symptom
  // is also what props-not-attributes blames on a different cause, so a reader
  // who has the invariants and not this line is steered to the wrong diagnosis.
  const entry = entryForTag(tag);
  const iface = el.name;
  const neverUpgrades =
    'If you skip registering it the element never upgrades: nothing renders, ' +
    '**no error and no warning is logged**, a property you set assigns and reads ' +
    `back correctly, and \`customElements.whenDefined('${tag}')\` never resolves.`;
  lines.push('', '### Getting the element');
  if (entry) {
    lines.push(
      `Register it before you use it. ${neverUpgrades}`,
      '',
      '```ts',
      "import '@kitn.ai/ui/elements';",
      `import '@kitn.ai/ui/elements/${entry}'; // or just this one`,
      '```',
    );
  } else {
    // entryForTag is undefined exactly when register-impl.ts does not import this
    // element's source file — i.e. it is NOT in the register-all bundle. The only
    // current instance is kai-remote, a deliberate exception (opt-in cross-origin
    // iframe card) documented in the "WHY THE MANIFEST AND NOT element-meta.json"
    // note in src/elements/element-diagnostics.ts, and at the `remote` entry in
    // `splitConfig()` in config/vite/elements.ts. `import '@kitn.ai/ui/elements'`
    // would NOT
    // register a tag in this state, so asserting it here is exactly the false
    // claim this section exists to prevent.
    //
    // The specifier is still NOT guessed — stripping `kai-` is wrong for ten of
    // the eighty elements. `optInEntryForTag` reads it off the module the
    // per-element build actually emitted, matched to this tag by the tag literal
    // it registers; see the note there. Telling the reader to go look it up was
    // the last place in this reference where "how to make the element exist" did
    // not answer itself, and the answer was in the build config all along.
    const optIn = optInEntryForTag(tag);
    lines.push(
      `**\`${tag}\` is opt-in — it is not part of \`import '@kitn.ai/ui/elements'\` ` +
        '(register-all), and that import alone will NOT register it.** ' +
        (optIn
          ? `Import its own entry point instead. ${neverUpgrades}`
          : // No built module claims this tag, so there is no specifier to name.
            // Stay honest rather than inventing one.
            'Find its specific `@kitn.ai/ui/elements/<name>` entry point in the ' +
            `package's published exports before using it. ${neverUpgrades}`),
    );
    if (optIn) {
      lines.push('', '```ts', `import '@kitn.ai/ui/elements/${optIn}';`, '```');
    }
  }
  if (iface) {
    lines.push(
      '',
      `TypeScript: \`import type { ${iface} } from '@kitn.ai/ui/elements';\` — ` +
        'the element interface ships with the package; do not hand-roll a structural type.',
    );
  }

  // ── Contract note ──────────────────────────────────────────────────────────
  lines.push(
    '',
    '### AI/UI contract',
    '`kai-*` elements accept **array and object data as JavaScript properties** ' +
      '(set in JavaScript via `el.property = value`, not as HTML attributes). ' +
      'Events are native CustomEvents — listen with `el.addEventListener("event-name", handler)` ' +
      'and read `event.detail` for the payload.',
  );

  // ── Card contract ─────────────────────────────────────────────────────────
  // Attached to the two populations manifest.ts derives, and to nothing else. A
  // reference that hangs card material off all 80 elements is worse than one that
  // hangs it off none: it teaches a harness that every element takes a tool call.
  const cardType = cardTypeForTag(tag);
  if (cardType !== undefined && isCardSchemaName(cardType)) {
    lines.push(...renderCardContract(tag, cardType, provider));
  } else if (cardHostTags().includes(tag)) {
    lines.push(...renderCardHost(tag));
  }

  // ── Public JS properties ───────────────────────────────────────────────────
  const publicFields = (el.members ?? []).filter(
    (m) => m.kind === 'field' && m.privacy === 'public',
  );

  if (publicFields.length > 0) {
    lines.push('', '### Props (JavaScript properties)');
    for (const field of publicFields) {
      const type = field.type?.text ?? 'unknown';
      const jsOnly = isJsOnlyType(type);
      const desc = field.description?.trim() ?? '';
      const note = jsOnly ? ' ⚑ set as a JS property, not an HTML attribute' : '';
      lines.push(`- **${field.name}** \`${type}\`${note}`);
      if (desc) {
        lines.push(`  ${desc}`);
      }
    }
  }

  // ── HTML attributes ────────────────────────────────────────────────────────
  const attrs = el.attributes ?? [];
  if (attrs.length > 0) {
    lines.push('', '### Attributes (HTML-safe)');
    for (const attr of attrs) {
      const type = attr.type?.text ?? 'unknown';
      const desc = attr.description?.trim() ?? '';
      lines.push(`- **${attr.name}** \`${type}\``);
      if (desc) {
        lines.push(`  ${desc}`);
      }
    }
  }

  // ── Events ────────────────────────────────────────────────────────────────
  const events = el.events ?? [];
  if (events.length > 0) {
    lines.push('', '### Events (CustomEvent, listen via addEventListener)');
    for (const ev of events) {
      const desc = ev.description?.trim() ?? '';
      const detail = eventDetail(ev.type?.text);
      lines.push(
        detail
          ? `- **${ev.name}** — ${desc} \`detail\`: \`${detail}\``
          : `- **${ev.name}** — ${desc}`,
      );
    }
  }

  // ── Methods ───────────────────────────────────────────────────────────────
  // The input half of the interaction surface. These were in the manifest and in
  // the shipped types and rendered in NO reference, so the only way to find one
  // was to read the kit's source.
  const methods = (el.members ?? []).filter(isPublicMethod);
  if (methods.length > 0) {
    lines.push(
      '',
      '### Methods (call these on the element instance)',
      `Get the element (\`const el = document.querySelector('${tag}')\`), then call it. ` +
        'Methods drive the element from your code; the events above report back what the ' +
        'user did. Both are public API.',
    );
    for (const method of methods) {
      const desc = method.description?.trim() ?? '';
      lines.push(`- **${methodSignature(method)}**${desc ? ` — ${desc}` : ''}`);
    }
  }

  // ── CSS custom properties ─────────────────────────────────────────────────
  const cssProps = el.cssProperties ?? [];
  if (cssProps.length > 0) {
    lines.push('', '### CSS custom properties');
    for (const prop of cssProps) {
      const desc = prop.description?.trim() ?? '';
      const def = prop.default ? ` (default: ${prop.default})` : '';
      lines.push(`- **${prop.name}**${def}${desc ? ` — ${desc}` : ''}`);
    }
  }

  // ── Composition slots ──────────────────────────────────────────────────────
  const slots = el.slots ?? [];
  if (slots.length > 0) {
    lines.push(
      '',
      '### Composition slots',
      'Project your own markup into these named regions — add a light-DOM child ' +
        'with a `slot="…"` attribute (e.g. `<div slot="sidebar">…</div>`).',
    );
    for (const slot of slots) {
      const desc = slot.description?.trim() ?? '';
      lines.push(`- **${slot.name}**${desc ? ` — ${desc}` : ''}`);
    }
  }

  // ── Styleable parts (::part) ───────────────────────────────────────────────
  const parts = el.cssParts ?? [];
  if (parts.length > 0) {
    lines.push(
      '',
      '### Styleable parts (`::part`)',
      'Restyle these from outside the Shadow DOM via `' + tag + '::part(name) { … }`.',
    );
    for (const part of parts) {
      const desc = part.description?.trim() ?? '';
      lines.push(`- **${part.name}**${desc ? ` — ${desc}` : ''}`);
      if (part.recipe) {
        lines.push('  ```css', `  ${part.recipe}`, '  ```');
      }
    }
  }

  // ── The composition catalog ────────────────────────────────────────────────
  lines.push(...catalogSectionLines(tag));

  return lines.join('\n');
}

export const reference: Tool = {
  name: 'component_reference',
  description:
    'Look up AI/UI (kai-*) web components: their tags, props, events, imperative methods, and usage examples. ' +
    'For a card-backed element it also returns the card\'s JSON Schema and a ready-to-send ' +
    'tool definition generated from it — pass `provider` to get that provider\'s envelope. ' +
    'Also serves the programmatic layer (name: "programmatic" — the @kitn.ai/ui/state + ' +
    '@kitn.ai/ui/wire streaming/mock/encode API) and complete code recipes ' +
    '(e.g. name: "composed-thread" — a hand-composed thread with no <kai-chat>).',
  inputSchema: z.object({
    name: z
      .string()
      .optional()
      .describe(
        'The element tag, e.g. "kai-chat". Omit it (or pass "list") to get the ' +
          'index of every element with a one-line summary, then ask again for the one you want. ' +
          'Pass "invariants" for the full diagnosis and wrong/right examples behind every ' +
          'invariant id an element lookup shows. Pass "recipes" for the full wiring notes ' +
          'behind every surface recipe an element lookup names. Pass "programmatic" (or ' +
          '"state" / "wire") for the @kitn.ai/ui/state + @kitn.ai/ui/wire API — streaming ' +
          'folds, the mock responder, the SSE readers/encoders. Pass a code-recipe id ' +
          '(e.g. "composed-thread") for a complete pasteable composition.',
      ),
    provider: z
      .enum(PROVIDERS)
      .optional()
      .describe(
        'Which tool-definition envelope to project for a card-backed element. ' +
          `Defaults to "${DEFAULT_PROVIDER}", the provider-neutral { name, description, schema } form.`,
      ),
  }),
  handler: async (args: Record<string, unknown>) => {
    const name = typeof args.name === 'string' ? args.name.trim() : undefined;

    // Validated HERE, not left to the zod schema above. server.ts advertises
    // `inputSchema` over the protocol but hands `request.params.arguments` straight
    // to this handler without parsing it, so an unrecognised provider would reach
    // `cardTools`, which treats anything that is not "openai"/"anthropic" as the
    // jsonschema branch. A caller asking for "gemini" would then get a definition in
    // a shape they did not ask for, with nothing saying so. Refusing is the only
    // answer that cannot be mistaken for an answer.
    const rawProvider = args.provider;
    if (rawProvider !== undefined && (typeof rawProvider !== 'string' || !isProvider(rawProvider))) {
      return {
        content: [
          {
            type: 'text' as const,
            text:
              `Unknown provider: ${JSON.stringify(rawProvider)}\n\n` +
              `Valid providers are ${PROVIDERS.map((p) => `"${p}"`).join(', ')}. ` +
              `Omit it to get "${DEFAULT_PROVIDER}", the provider-neutral { name, description, schema } form ` +
              'that the Vercel AI SDK and most agent frameworks take directly.\n' +
              'No tool definition was returned, because guessing which envelope you meant would hand you ' +
              'a shape your provider rejects with nothing saying why.',
          },
        ],
      };
    }
    const provider: ToolProvider = rawProvider ?? DEFAULT_PROVIDER;

    let text: string;

    if (!name || name === 'list') {
      const tags = listElements();
      const cardRows = cardSchemaNames
        .map((t) => cardTagForType(t))
        .filter((t): t is string => t !== undefined);
      text =
        `AI/UI elements (${tags.length} total):\n\n` +
        tags.map((t) => `  ${t}`).join('\n') +
        '\n\nCall component_reference with a specific name (e.g. { name: "kai-chat" }) for full API details.' +
        `\n\nCard-backed elements — ask for one of these to get its JSON Schema and a generated ` +
        `\`${KAI_TOOL_PREFIX}*\` tool definition:\n  ${cardRows.join(', ')}` +
        `\nThe elements that HOST them (and carry the \`cardTypes\` / \`cardSchemas\` props): ${cardHostTags().join(', ')}` +
        `\n\nCall component_reference with { name: "invariants" } for the full diagnosis and ` +
        'wrong/right examples behind every invariant id shown on an element lookup.' +
        `\n\nCall component_reference with { name: "recipes" } for the full wiring notes behind ` +
        'every surface recipe an element lookup names.' +
        `\n\nCall component_reference with { name: "programmatic" } for the @kitn.ai/ui/state + ` +
        '@kitn.ai/ui/wire API — createAssistantStream, the part folds, createMockResponder ' +
        '(and its scripted tool calls), the SSE readers and the provider encoders. That layer ' +
        'is what a host wires when it composes elements by hand instead of using <kai-chat>.' +
        `\n\nComplete pasteable compositions (code recipes): ${listCodeRecipes()
          .map((r) => `{ name: "${r.id}" } — ${r.title}`)
          .join('; ')}.`;
    } else if (name === 'invariants') {
      text = renderInvariantAppendix().join('\n');
    } else if (name === 'recipes') {
      text = renderRecipeAppendix().join('\n');
    } else if ((PROGRAMMATIC_ALIASES as readonly string[]).includes(name)) {
      text = renderProgrammaticAppendix();
    } else if (getCodeRecipe(name)) {
      text = renderCodeRecipe(getCodeRecipe(name)!);
    } else {
      text = formatReference(name, provider);
    }

    return { content: [{ type: 'text' as const, text }] };
  },
};
