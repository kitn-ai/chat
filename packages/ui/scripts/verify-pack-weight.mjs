// Guards the published tarball against dead weight.
//
// WHY: `files` in package.json ships the whole of `src/` on purpose — consumers
// read source and source maps point into it. That blanket include is also how
// 300 KB of generated JSON (`src/components/component-meta.json`) rode along to
// every consumer for months: nothing imported it, the `exports` map could not
// even reach it, and no existing check looked at what actually gets packed.
//
// WHAT IT CHECKS:
//
//   1. PRECISE — every packed file OUTSIDE `dist/` larger than MAX_FILE_BYTES
//      must be named in ALLOWED_LARGE_FILES, with a reason. Hand-authored and
//      generated-into-source paths are stable, so an exact allowlist works here
//      and names the offender when it trips. Adding a new large artifact under
//      `src/` is then a deliberate, reviewable act instead of an accident.
//
//      `dist/` is deliberately exempt from this rule: its chunk names carry
//      content hashes that change on every build, so an exact allowlist over
//      them would go red on every rebuild and get bumped reflexively — a check
//      that proves nothing. Rule 2 covers dist.
//
//   2. CRUDE — total unpacked size must stay under MAX_UNPACKED_BYTES. Cruder
//      than rule 1 and it names nothing, but it is the backstop for growth that
//      rule 1 cannot see: many small files, or bundle bloat inside `dist/`.
//
// Run it AFTER a build. Without `dist/` the tarball is a fraction of its real
// size and both rules would pass vacuously, so a missing `dist/` is a failure,
// not a skip.
//
// Usage: node scripts/verify-pack-weight.mjs

import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Anything bigger than this, outside dist/, needs an explicit entry below. */
const MAX_FILE_BYTES = 64 * 1024;

/**
 * Packed files over MAX_FILE_BYTES that are meant to ship, and why. Paths are
 * relative to the package root, exactly as `npm pack` reports them.
 *
 * Before adding an entry, check the file is genuinely REACHABLE by a consumer:
 * an `exports` subpath, an import from shipped code, or documented source that
 * someone reads. "It is generated by the build" is not a reason to ship it.
 */
const ALLOWED_LARGE_FILES = new Map([
  ['src/elements/element-meta.json', 'exported as the `./element-meta.json` subpath'],
  ['src/elements/element-types.d.ts', 'source copy of the JSX intrinsics; consumers reference it'],
  ['llms-full.txt', 'shipped LLM context, listed explicitly in `files`'],
  ['src/agent-tooling/mcp/tools/scaffold.ts', 'source of the `kai` MCP scaffolder'],
  ['frameworks/react/index.tsx', 'source of the generated React wrappers'],
  ['src/elements/compiled.css', 'the shadow-DOM stylesheet the elements adopt'],
]);

/**
 * Backstop ceiling on total unpacked size. Headroom over the current figure is
 * deliberate — this should catch a step change, not normal drift. Raise it only
 * with a note saying what grew and that the growth is genuinely needed.
 */
const MAX_UNPACKED_BYTES = 12.5 * 1024 * 1024;

const kib = (n) => `${(n / 1024).toFixed(1)} KiB`;
const mib = (n) => `${(n / 1024 / 1024).toFixed(2)} MiB`;

if (!existsSync(resolve(ROOT, 'dist'))) {
  console.error(
    '\n✗ pack weight: dist/ is missing, so the packed tarball would be a fraction of\n' +
      '  its real size and this check would pass without proving anything.\n\n' +
      '  Build first:  nx build ui\n',
  );
  process.exit(1);
}

// --ignore-scripts: `npm pack` would otherwise run prepublishOnly (a full
// rebuild) just to list files.
const raw = execFileSync('npm', ['pack', '--dry-run', '--ignore-scripts', '--json'], {
  cwd: ROOT,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
  stdio: ['ignore', 'pipe', 'ignore'],
});

const report = JSON.parse(raw.slice(raw.indexOf('[')))[0];
const files = report.files ?? [];

if (files.length === 0) {
  console.error('\n✗ pack weight: `npm pack --dry-run` reported no files. Cannot verify.\n');
  process.exit(1);
}

const failures = [];

// --- Rule 1: large non-dist files must be allowlisted -----------------------
const unexpected = files
  .filter((f) => !f.path.startsWith('dist/') && f.size > MAX_FILE_BYTES)
  .filter((f) => !ALLOWED_LARGE_FILES.has(f.path))
  .sort((a, b) => b.size - a.size);

if (unexpected.length > 0) {
  const total = unexpected.reduce((sum, f) => sum + f.size, 0);
  failures.push(
    `${unexpected.length} unexpected file(s) over ${kib(MAX_FILE_BYTES)} in the tarball ` +
      `(${kib(total)} total):\n` +
      unexpected.map((f) => `      ${kib(f.size).padStart(10)}  ${f.path}`).join('\n') +
      '\n\n' +
      '    Every consumer downloads these. If a file is unreachable through the\n' +
      '    `exports` map and nothing imports it, exclude it with a negation in the\n' +
      '    `files` array of package.json, e.g. "!src/path/to/file.json".\n' +
      '    If it genuinely must ship, add it to ALLOWED_LARGE_FILES in\n' +
      '    scripts/verify-pack-weight.mjs with the reason it is reachable.',
  );
}

// --- Rule 2: total unpacked size ceiling ------------------------------------
if (report.unpackedSize > MAX_UNPACKED_BYTES) {
  failures.push(
    `unpacked size ${mib(report.unpackedSize)} exceeds the ${mib(MAX_UNPACKED_BYTES)} ceiling ` +
      `(over by ${mib(report.unpackedSize - MAX_UNPACKED_BYTES)}).\n\n` +
      '    Find what grew:  npm pack --dry-run --ignore-scripts --json | ...\n' +
      '    Then either drop it from `files`, or raise MAX_UNPACKED_BYTES in\n' +
      '    scripts/verify-pack-weight.mjs with a note on what grew and why.',
  );
}

if (failures.length > 0) {
  console.error('\n✗ pack weight:\n');
  for (const f of failures) console.error(`  - ${f}\n`);
  process.exit(1);
}

const stale = [...ALLOWED_LARGE_FILES.keys()].filter(
  (p) => !files.some((f) => f.path === p && f.size > MAX_FILE_BYTES),
);

console.log(
  `✓ pack weight: ${report.entryCount} files, ${mib(report.unpackedSize)} unpacked ` +
    `(ceiling ${mib(MAX_UNPACKED_BYTES)}); every non-dist file over ${kib(MAX_FILE_BYTES)} ` +
    `is one of the ${ALLOWED_LARGE_FILES.size} allowlisted.`,
);

if (stale.length > 0) {
  console.log(
    `  note: ${stale.length} allowlist entr${stale.length === 1 ? 'y is' : 'ies are'} no longer ` +
      `packed over ${kib(MAX_FILE_BYTES)} and can be dropped: ${stale.join(', ')}`,
  );
}
