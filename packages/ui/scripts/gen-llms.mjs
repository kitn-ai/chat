const STREAMING_RECIPE = `## Streaming recipe (critical)

Two rules, and both bite:

1. **Reassign a NEW array containing a NEW message object on every chunk.** Mutating an existing message object in place will NOT trigger a re-render.
2. **Fold the delta onto the message's TRAILING text part.** Replacing \`parts\` with a fresh single-text array re-renders fine but silently deletes any reasoning / tool / card parts the turn already produced.

\`\`\`js
// The fold. \`@kitn.ai/ui/state\` exports exactly this as \`appendTextPart\`.
const appendText = (parts, delta) => {
  const last = parts[parts.length - 1];
  return last?.type === 'text'
    ? [...parts.slice(0, -1), { ...last, text: last.text + delta }]
    : [...parts, { type: 'text', text: delta }];
};

// ✅ re-renders, and keeps every part already on the message
chat.messages = chat.messages.map((m) =>
  m.id === id ? { ...m, parts: appendText(m.parts, delta) } : m);

// ❌ does NOT re-render (same array, same object)
chat.messages[i].parts = appendText(chat.messages[i].parts, delta);

// ❌ re-renders, but drops the message's reasoning/tool/card parts
chat.messages = chat.messages.map((m) =>
  m.id === id ? { ...m, parts: [{ type: 'text', text: answer }] } : m);
\`\`\`

Opening a new text part when the last part is not text is what stops a post-tool answer being glued onto the pre-tool text.

The same reassign rule applies to every array/object property (\`models\`, \`context\`, \`suggestions\`, …): replace, don't mutate.`;

// ---------------------------------------------------------------------------
// Normalize the data model: accept either the in-memory `elements` array from
// gen-element-api.mjs OR the dist/custom-elements.json declarations.
// ---------------------------------------------------------------------------
function fromElements(elements) {
  return elements.map((el) => ({
    tag: el.tag,
    reactName: el.displayName ?? tagToReact(el.tag).replace(/^Kai/, ''),
    props: el.props.map((p) => ({
      name: p.name,
      type: p.type,
      scalar: p.scalar,
      description: p.description,
    })),
    events: el.events.map((e) => ({
      name: e.name,
      detail: e.detail ? `CustomEvent<${e.detail}>` : 'CustomEvent',
      description: e.description,
    })),
    methods: (el.methods ?? []).map((m) => ({
      name: m.name,
      params: m.params,
      returns: m.returns,
      description: m.description,
    })),
    slots: el.slots,
    parts: el.parts,
    declarativeChildren: el.declarativeChildren,
  }));
}

function fromManifest(cem) {
  const decls = cem.modules[0].declarations;
  return decls.map((d) => {
    const attrByField = new Map(
      (d.attributes || []).filter((a) => a.fieldName).map((a) => [a.fieldName, a]),
    );
    return {
      tag: d.tagName,
      reactName: tagToReact(d.tagName).replace(/^Kai/, ''),
      props: (d.members || [])
        .filter((m) => m.kind === 'field')
        .map((m) => ({
          name: m.name,
          type: m.type?.text ?? 'unknown',
          scalar: attrByField.has(m.name) || isScalarType(m.type?.text ?? ''),
          description: m.description ?? '',
        })),
      events: (d.events || []).map((e) => ({
        name: e.name,
        detail: e.type?.text ?? 'CustomEvent',
        description: e.description ?? '',
      })),
      // Must stay in step with `fromElements` above. This path is the standalone
      // fallback, and a field it forgets does not fail — it silently writes a
      // THINNER llms-full.txt over the full one (see the header note and CLAUDE.md).
      // The CEM packs the whole authored parameter list into `parameters[0].name`.
      methods: (d.members || [])
        .filter((m) => m.kind === 'method')
        .map((m) => ({
          name: m.name,
          params: m.parameters?.[0]?.name ?? '',
          returns: m.return?.type?.text ?? 'void',
          description: m.description ?? '',
        })),
      slots: (d.slots || []).map((s) => ({ name: s.name, doc: s.description ?? '' })),
      parts: (d.cssParts || []).map((p) => ({ name: p.name, doc: p.description ?? '', recipe: p.recipe })),
      declarativeChildren: (d.declarativeChildren || []).map((c) => ({
        tag: c.tagName,
        attributes: (c.attributes || []).map((a) => a.name),
        text: !!c.textContent,
        description: c.description ?? '',
      })),
    };
  });
}

export function generate(elementsInput) {
  const els = elementsInput ? fromElements(elementsInput) : fromManifest(
    JSON.parse(readFileSync(resolve(root, 'dist/custom-elements.json'), 'utf8')),
  );
  els.sort((a, b) => a.tag.localeCompare(b.tag));
  const count = els.length;

  const llmsBody = buildLlmsBody(count);
  const llmsTxt = `${HEADER_NOTE}\n${llmsBody}\n`;

  const elementSection = els.map(renderElement).join('\n\n');
  // Derived from dist/state/*.d.ts + dist/wire/*.d.ts — the layer a builder
  // that leaves <kai-chat> writes against, previously on no surface (F-46).
  const programmatic = buildProgrammaticSection();
  const llmsFull = [
    HEADER_NOTE,
    '# @kitn.ai/ui — Full Reference',
    '',
    llmsBody,
    '',
    '---',
    '',
    RUNBOOK,
    '',
    '---',
    '',
    STREAMING_RECIPE,
    '',
    '---',
    '',
    programmatic.markdown,
    '',
    '---',
    '',
    `## Element reference (${count} elements, generated from custom-elements.json)`,
    '',
    'Every element also accepts the `theme` attribute. Array/object properties are marked with a `—` attribute: they must be set as JS properties.',
    '',
    elementSection,
    '',
  ].join('\n') + '\n';

  mkdirSync(resolve(root, 'dist/llms'), { recursive: true });
  writeFileSync(resolve(root, 'llms.txt'), llmsTxt);
  writeFileSync(resolve(root, 'llms-full.txt'), llmsFull);
  writeFileSync(resolve(root, 'dist/llms/llms.txt'), llmsTxt);
  writeFileSync(resolve(root, 'dist/llms/llms-full.txt'), llmsFull);
  // NO standalone programmatic.md: the MCP's { name: "programmatic" } topic
  // slices the marker-fenced section back out of dist/llms/llms-full.txt, so
  // a separate copy would be ~50 KB of duplicate tarball weight (verify:pack
  // is the guard that priced it). Remove a stale copy from earlier builds so
  // it cannot keep shipping — dist/ is packed wholesale.
  rmSync(resolve(root, 'dist/llms/programmatic.md'), { force: true });

  console.log(
    `✓ llms.txt + llms-full.txt written (${count} elements, ${programmatic.exportCount} state/wire exports)`,
  );
  return count;
}

