/**
 * The feature multi-select — the CLI's surface axis.
 *
 * Each feature is a name for a `kai-*` components list. That is the whole
 * mapping, and it is what lets any combination be reachable instead of only the
 * six someone thought to name: the archetypes in the kit's catalog are six
 * points in this space, and `renderSurface` takes the list rather than a preset
 * id precisely so the rest of the space is expressible.
 *
 * WHAT IS DECLARED HERE AND WHY IT IS NOT A RESTATEMENT. The components are the
 * CLI's own product decision — "conversation history means a sidebar plus a
 * resizable split" is a UX call, not a fact the catalog holds. What is NOT
 * declared here is whether a feature can actually be emitted: that is computed
 * against `rendererComponents()` and the framework's template, so a feature
 * whose components no renderer branches on is reported as unavailable rather
 * than emitted into a project that silently lacks it.
 */
import { rendererComponents } from './catalog';
import type { FrameworkDef } from './frameworks';

export interface FeatureDef {
  id: string;
  label: string;
  hint: string;
  /** the `kai-*` components this feature composes */
  components: readonly string[];
  /** ticked when the user presses Enter through the prompt */
  default: boolean;
}

